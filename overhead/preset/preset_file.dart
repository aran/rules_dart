/// Where the preset goes, relative to the checkout root.
const presetPath = 'tools/preset.bazelrc';

const _generatorHeader = '# Generated by bazelrc-preset.bzl';

/// The header the written file carries, naming the command that writes it.
const header =
    '$_generatorHeader, at the version overhead pins.\n'
    '# To update this file, run:\n'
    '#   bazel run @overhead//preset\n';

/// The preset file for [generated], the output of bazelrc-preset.bzl's
/// `generate_preset`: its header, which names overhead's internal label,
/// becomes [header].
String presetFile(String generated) {
  if (!generated.startsWith(_generatorHeader)) {
    throw FormatException(
      'bazelrc-preset.bzl output no longer starts with "$_generatorHeader"',
    );
  }
  // The header is the comment lines before the first blank one.
  final end = generated.indexOf('\n\n');
  if (end < 0) {
    throw const FormatException(
      'bazelrc-preset.bzl output has no blank line after its header',
    );
  }
  return header + generated.substring(end + 1);
}

/// Why [actual], the checked-in preset (null when there is none), is not
/// [want]; null when it is.
String? staleness(String? actual, String want) {
  const fix = 'run `bazel run @overhead//preset`';
  if (actual == null) return '$presetPath is missing; $fix';
  if (actual != want) return '$presetPath is out of date; $fix';
  return null;
}
