// Run from this directory: `dart check.dart`.
//
// Property: an archive downloaded from a pub registry cannot make the fetched
// package refer to, or write to, anything outside the package. Each hostile
// archive is served from a `file://` registry in a temp dir; for each, the
// fetch may either be refused or succeed, but afterwards
//   * no symlink in the package points outside the package,
//   * nothing was written outside the package (absolute or `..` entry names),
//   * no host file was hard-linked or written into the package, and
//   * nothing was written through a symlink entry.
// The control package must fetch with its in-package symlink, so "everything
// was refused" or "every link was dropped" cannot pass. As pub does, an
// archive with an absolute or `..` entry name is refused outright, and one
// with an escaping symlink fetches without that link.
import 'dart:convert';
import 'dart:io';

const _repoPrefix = 'rules_dart++pub+dart_pub__';

class _Entry {
  _Entry(this.name, this.type, {this.data = const [], this.link = ''});
  final String name;
  final String type; // '0' file, '1' hard link, '2' symlink
  final List<int> data;
  final String link;
}

void _field(List<int> header, int offset, int length, String value) {
  final bytes = utf8.encode(value);
  if (bytes.length > length) throw ArgumentError('$value too long');
  header.setRange(offset, offset + bytes.length, bytes);
}

List<int> _tar(List<_Entry> entries) {
  final out = <int>[];
  for (final e in entries) {
    final header = List<int>.filled(512, 0);
    _field(header, 0, 100, e.name);
    _field(header, 100, 8, '0000644\u0000');
    _field(header, 108, 8, '0000000\u0000');
    _field(header, 116, 8, '0000000\u0000');
    _field(
      header,
      124,
      12,
      '${e.data.length.toRadixString(8).padLeft(11, '0')}\u0000',
    );
    _field(header, 136, 12, '00000000000\u0000');
    header.setRange(148, 156, List<int>.filled(8, 0x20));
    header[156] = e.type.codeUnitAt(0);
    _field(header, 157, 100, e.link);
    _field(header, 257, 6, 'ustar\u0000');
    _field(header, 263, 2, '00');
    final sum = header.fold<int>(0, (a, b) => a + b);
    _field(header, 148, 8, '${sum.toRadixString(8).padLeft(6, '0')}\u0000 ');
    out
      ..addAll(header)
      ..addAll(e.data)
      ..addAll(List<int>.filled((512 - e.data.length % 512) % 512, 0));
  }
  out.addAll(List<int>.filled(1024, 0));
  return out;
}

String _sha256(String path) {
  for (final cmd in [
    ['shasum', '-a', '256', path],
    ['sha256sum', path],
  ]) {
    try {
      final r = Process.runSync(cmd.first, cmd.sublist(1));
      if (r.exitCode == 0) return (r.stdout as String).split(' ').first;
    } on ProcessException {
      // try the next one
    }
  }
  throw StateError('no sha256 tool found');
}

/// Collapses `.` and `..` segments of an absolute path.
String _normalize(String path) {
  final out = <String>[];
  for (final s in path.split('/')) {
    if (s.isEmpty || s == '.') continue;
    if (s == '..') {
      if (out.isNotEmpty) out.removeLast();
    } else {
      out.add(s);
    }
  }
  return '/${out.join('/')}';
}

Future<void> main() async {
  final here = Directory.current.path;
  final tmp = Directory(
    Directory.systemTemp
        .createTempSync('pub_archive_links')
        .resolveSymbolicLinksSync(),
  );
  final victim = Directory('${tmp.path}/victim')..createSync();
  File('${victim.path}/secret.txt').writeAsStringSync('TOPSECRET\n');
  final absWritten = '${tmp.path}/abs_written';

  List<int> pubspec(String n) => utf8.encode(
    'name: $n\nversion: 1.0.0\nenvironment:\n  sdk: ">=3.0.0 <4.0.0"\n',
  );
  final packages = <String, List<_Entry>>{
    'control': [
      _Entry('lib/a.dart', '0', data: utf8.encode('int a = 1;\n')),
      _Entry('lib/in.dart', '2', link: 'a.dart'),
    ],
    'link_relative_escape': [_Entry('lib/esc', '2', link: '../../../x')],
    'link_absolute': [_Entry('lib/abs', '2', link: '/etc/passwd')],
    'write_through_link': [
      _Entry('lib/d', '2', link: victim.path),
      _Entry('lib/d/evil', '0', data: utf8.encode('pwned\n')),
    ],
    'hardlink_absolute': [
      _Entry('lib/h', '1', link: '${victim.path}/secret.txt'),
    ],
    'entry_absolute_path': [
      _Entry(absWritten, '0', data: utf8.encode('pwned\n')),
    ],
    'entry_dotdot_path': [
      _Entry('../dotdot_written', '0', data: utf8.encode('pwned\n')),
      _Entry('../../dotdot_written2', '0', data: utf8.encode('pwned\n')),
    ],
    'entry_dotdot_inner': [
      _Entry('lib/../../inner_written', '0', data: utf8.encode('pwned\n')),
    ],
  };

  final lock = StringBuffer('# Generated by check.dart\npackages:\n');
  for (final name in packages.keys) {
    final dir = Directory('${tmp.path}/registry/packages/$name/versions')
      ..createSync(recursive: true);
    final archive = File('${dir.path}/1.0.0.tar.gz');
    archive.writeAsBytesSync(
      gzip.encode(
        _tar([
          _Entry('pubspec.yaml', '0', data: pubspec(name)),
          ...packages[name]!,
        ]),
      ),
    );
    lock.write('''
  $name:
    dependency: "direct main"
    description:
      name: $name
      sha256: "${_sha256(archive.path)}"
      url: "file://${tmp.path}/registry"
    source: hosted
    version: "1.0.0"
''');
  }
  lock.write('sdks:\n  dart: ">=3.11.0 <4.0.0"\n');
  File('$here/generated.lock').writeAsStringSync(lock.toString());

  final repos = [for (final n in packages.keys) '--repo=@@$_repoPrefix$n'];
  final fetch = Process.runSync('bazel', [
    'fetch',
    // generated.lock names a temporary registry; recording it would put this
    // run's temp paths in the committed MODULE.bazel.lock.
    '--lockfile_mode=off',
    '--keep_going',
    '--noshow_progress',
    '--curses=no',
    '--color=no',
    ...repos,
  ], workingDirectory: here);
  final info = Process.runSync('bazel', [
    'info',
    'output_base',
  ], workingDirectory: here);
  final outputBase = Directory((info.stdout as String).trim())
      .resolveSymbolicLinksSync();
  stdout.writeln('output_base: $outputBase');

  final violations = <String>[];
  void expect(bool ok, String what) {
    if (!ok) violations.add(what);
  }

  // Nothing outside any package changed.
  expect(
    !File(absWritten).existsSync(),
    'an absolute entry name wrote $absWritten',
  );
  expect(
    !File('$outputBase/external/dotdot_written').existsSync(),
    'a ../ entry wrote outside its repository',
  );
  expect(
    !File('$outputBase/dotdot_written2').existsSync(),
    'a ../../ entry wrote outside the external directory',
  );
  expect(
    !File('$outputBase/external/inner_written').existsSync(),
    'a lib/../../ entry wrote outside its repository',
  );
  final victimFiles =
      victim
          .listSync()
          .map((e) => e.uri.pathSegments.where((s) => s.isNotEmpty).last)
          .toList()
        ..sort();
  expect(
    victimFiles.length == 1 && victimFiles.single == 'secret.txt',
    'an entry was written through a symlink into ${victim.path}: $victimFiles',
  );

  // pub refuses these archives; the rest of the hostile ones it fetches
  // without the offending link, so they must fetch here too.
  const mustRefuse = {
    'entry_absolute_path',
    'entry_dotdot_path',
    'entry_dotdot_inner',
  };
  const mustFetch = {'control', 'link_relative_escape', 'link_absolute'};
  for (final name in packages.keys) {
    final repo = Directory('$outputBase/external/$_repoPrefix$name');
    if (!repo.existsSync()) {
      expect(
        !mustFetch.contains(name),
        '$name was not fetched:\n${fetch.stderr}',
      );
      stdout.writeln('$name: refused');
      continue;
    }
    stdout.writeln('$name: fetched');
    expect(!mustRefuse.contains(name), '$name was fetched, not refused');
    final root = _normalize(repo.path);
    for (final e in repo.listSync(recursive: true, followLinks: false)) {
      if (e is Link) {
        final target = e.targetSync();
        final resolved = _normalize(
          target.startsWith('/') ? target : '${e.parent.path}/$target',
        );
        expect(
          resolved == root || resolved.startsWith('$root/'),
          '$name: ${e.path.substring(root.length)} -> $target leaves the package',
        );
      } else if (e is File && e.path.endsWith('/lib/h')) {
        expect(
          !e.readAsStringSync().contains('TOPSECRET'),
          '$name: a host file was hard-linked into the package',
        );
      }
    }
    if (name == 'control') {
      expect(
        File('${repo.path}/lib/a.dart').existsSync(),
        'control: lib/a.dart is missing',
      );
      // pub keeps a link that stays inside the package.
      expect(
        Link('${repo.path}/lib/in.dart').existsSync(),
        'control: the in-package link lib/in.dart was dropped',
      );
    }
  }

  tmp.deleteSync(recursive: true);
  File('$here/generated.lock').deleteSync();
  if (violations.isNotEmpty) {
    stderr.writeln(
      '\nFAIL: a fetched pub archive can reach outside its package:',
    );
    for (final v in violations) {
      stderr.writeln('  - $v');
    }
    exit(1);
  }
  stdout.writeln('OK: no fetched archive reaches outside its package');
}
