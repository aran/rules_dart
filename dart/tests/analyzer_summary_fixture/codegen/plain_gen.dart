// A generator that is not built on the builder shim. It speaks the worker
// protocol `dart_codegen` requires of a `generator_bin`, and accepts the shim's
// flags and no others, as a user's own generator may. `dart_codegen` must pass
// it no analyzer summary flags, so it runs with the unchanged command line, and
// fails here if it gets one.
import 'dart:async';
import 'dart:io';

import 'package:bazel_worker/bazel_worker.dart';

const _flags = {
  '--input',
  '--input-asset',
  '--input-asset-extra',
  '--output',
  '--package',
  '--dep',
  '--part',
  '--config',
  '--package-config',
  '--root-language-version',
  '--sdk-path',
};

Future<void> main(List<String> argv) async {
  if (argv.contains('--persistent_worker')) {
    await _PlainWorker().run();
    return;
  }
  final args = <String>[];
  for (final a in argv) {
    if (a.startsWith('@')) {
      args.addAll(
        File(a.substring(1)).readAsLinesSync().where((l) => l.isNotEmpty),
      );
    } else {
      args.add(a);
    }
  }
  exitCode = _run(args, stderr.writeln);
}

class _PlainWorker extends AsyncWorkerLoop {
  @override
  Future<WorkResponse> performRequest(WorkRequest request) async {
    final buf = StringBuffer();
    final exit = _run(request.arguments, buf.writeln);
    return WorkResponse()
      ..exitCode = exit
      ..output = buf.toString();
  }
}

/// Writes one file per `--output`, or returns 64 on a flag outside the shim's set.
int _run(List<String> args, void Function(String) diagnostic) {
  final outputs = <String>[];
  var i = 0;
  while (i < args.length) {
    final flag = args[i];
    if (!_flags.contains(flag)) {
      diagnostic('plain_gen: unknown flag $flag');
      return 64;
    }
    if (flag == '--output') outputs.add(args[i + 1]);
    i += 2;
  }
  for (final out in outputs) {
    File(out).writeAsStringSync('// Generated by plain_gen.\n');
  }
  return 0;
}
