/// Stands in for a real builder in the codegen fixtures: writes each declared
/// output with the `content` option, an empty library unless a fixture says
/// otherwise. The fixtures assert at analysis time; the outputs exist so that
/// a library collecting them builds.
library;

import 'package:build/build.dart';
import 'package:rules_dart_ext/worker_entry.dart';

Future<void> main(List<String> args) => shimMain(args, _FixtureBuilder.new);

class _FixtureBuilder implements Builder {
  _FixtureBuilder(BuilderOptions options)
    : _content =
          options.config['content'] as String? ??
          '// Generated by the fixture.\n';

  final String _content;

  // The shim takes the outputs from the rule's declared ones.
  @override
  Map<String, List<String>> get buildExtensions => const {
    '.dart': ['.g.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    for (final output in buildStep.allowedOutputs) {
      await buildStep.writeAsString(output, _content);
    }
  }
}
